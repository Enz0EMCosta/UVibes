export const convertDemoToSpotifyTrack = (demo: DemoSong): SpotifyTrack => ({
  id: demo.id,
  name: demo.name,
  duration_ms: demo.durationMs,
  popularity: demo.popularity,
  artists: [{ id: `art-${demo.id}`, name: demo.artist, type: 'artist', uri: `spotify:artist:${demo.id}` }],
  album: {
    id: `alb-${demo.id}`,
    name: demo.album,
    images: [{ url: demo.cover }],
    artists: [{ id: `art-${demo.id}`, name: demo.artist, type: 'artist', uri: `spotify:artist:${demo.id}` }],
  },
  uri: `spotify:track:${demo.id}`,
  external_urls: { spotify: demo.spotifyUrl },
});

export const getDemoRecommendationsForTempo = (targetTempo: number): SpotifyTrack[] => {
  const sorted = [...DEMO_RECOMMENDATIONS_POOL].sort((a, b) => {
    const diffA = Math.abs(a.tempo - targetTempo);
    const diffB = Math.abs(b.tempo - targetTempo);
    return diffA - diffB;
  });

  return sorted.slice(0, 6).map((item) => item.track);
};
